import javacard.security.RandomData;

/**
 * EntropyProbe - an OPEN probe for the random generator of a Java Card secure element.
 *
 * WHY THIS EXISTS. A bearer instrument is only worth what its keys are worth, and its keys are
 * only worth what the generator that produced them is worth. That claim should not rest on the
 * vendor's word, nor on the word of whoever wrote the closed applet that holds the money. This
 * applet lets ANYONE pull as much output as they like from the same generator and run it
 * through their own statistical batteries.
 *
 * IT IS DELIBERATELY BORING, and every one of these is a property you can check by reading:
 *
 *   - It writes NO persistent memory. Not one byte. So it cannot be worn out, and you can pull
 *     gigabytes through it without consuming the endurance of the chip.
 *   - It keeps NO state between commands, and it holds NO secret.
 *   - It authenticates nobody and protects nothing, because it has nothing to protect.
 *   - It uses ONLY the standard Java Card API: javacard.framework and javacard.security.
 *     No vendor-proprietary package is imported, which is what lets this source be published.
 *
 * WHAT IT PROVES AND WHAT IT DOES NOT. It lets you measure the quality of the generator on this
 * chip. It does NOT prove that any other applet on any other card uses that generator
 * correctly. Those are two different claims and only the first one is in scope here.
 *
 *
 * ABOUT THE ALGORITHM IDENTIFIER, WHICH IS THE PART PEOPLE MISREAD
 *
 * This applet asks the platform for RandomData.ALG_PSEUDO_RANDOM.
 *
 * Do not read that name as "a software pseudorandom generator". On JCOP 4.x every RandomData
 * identifier maps to the SAME engine, and that engine is a DRG.4 certified DRBG under AIS 20,
 * seeded and continuously reseeded from the chip's physical true random source. The identifier
 * picks an API label; it does not select a source.
 *
 * ALG_PSEUDO_RANDOM is the identifier NXP recommends IN WRITING, in the JCOP 4 manual, section
 * 4.2.5.8 - the same section that declares the single mapping. The manual's words are: "It is
 * proposed to use ALG_PSEUDO_RANDOM."
 *
 * It is also measurable, and it was measured on a J3R180 before this applet was written:
 * generating 8 KB inside the card, all six identifiers cost the same per 32 bytes - 6.647,
 * 6.647, 6.646, 6.646, 6.696 and 6.652 ms. A software PRNG, a DRBG and a raw TRNG do not agree
 * to the third decimal. That timing is also the reason the call is slow: the operating system
 * runs continuous statistical tests over the physical source and waits to collect entropy. The
 * slowness is the guarantee, not a symptom.
 *
 * The XAKA applet uses this same identifier for this same reason, so a battery run against this
 * probe is measuring the same engine that produces XAKA key material.
 *
 *
 * COMMANDS
 *
 *   00 B0 00 00 Le     GET RANDOM     returns Le bytes (1..255; Le = 0 means 256)
 *   00 B2 00 00 00     DESCRIBE       returns the ASCII declaration above, in short form
 *   00 B4 00 00 01     ALGORITHM      returns 1 byte: the RandomData constant actually used
 *   00 B6 00 00 00     NOTICE         returns the attribution notice (Apache-2.0 s.4(d))
 *
 * Nothing else is implemented. Any other INS returns 6D00.
 */
