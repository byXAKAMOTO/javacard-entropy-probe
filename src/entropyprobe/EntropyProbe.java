    private final RandomData rng;

    private EntropyProbe() {
        // If the platform cannot give us this algorithm, FAIL. There is no fallback on
        // purpose: a probe that silently measured a different engine than the one it names
        // would be worse than no probe at all.
        rng = RandomData.getInstance(ALG_USED);
    }

    public static void install(byte[] bArray, short bOffset, byte bLength) {
        new EntropyProbe().register(bArray, (short) (bOffset + 1), bArray[bOffset]);
    }

    public void process(APDU apdu) {
        if (selectingApplet()) {
            return;
        }
        byte[] buf = apdu.getBuffer();
        if (buf[ISO7816.OFFSET_CLA] != (byte) 0x00) {
            ISOException.throwIt(ISO7816.SW_CLA_NOT_SUPPORTED);
        }

        switch (buf[ISO7816.OFFSET_INS]) {

            case INS_GET_RANDOM: {
                // Le = 0 means 256 in the ISO convention, and 256 does not fit in a byte, so
                // it is handled explicitly instead of wrapping around to zero bytes.
                short n = (short) (buf[ISO7816.OFFSET_LC] & 0x00FF);
                if (n == 0) {
                    n = 256;
                }
                rng.generateData(buf, (short) 0, n);
                apdu.setOutgoingAndSend((short) 0, n);
                return;
            }

            case INS_DESCRIBE:
                Util.arrayCopyNonAtomic(DECLARACION, (short) 0, buf, (short) 0,
                        (short) DECLARACION.length);
                apdu.setOutgoingAndSend((short) 0, (short) DECLARACION.length);
                return;

            case INS_NOTICE:
                Util.arrayCopyNonAtomic(AVISO, (short) 0, buf, (short) 0,
                        (short) AVISO.length);
                apdu.setOutgoingAndSend((short) 0, (short) AVISO.length);
                return;

            case INS_ALGORITHM:
                buf[0] = ALG_USED;
                apdu.setOutgoingAndSend((short) 0, (short) 1);
                return;

            default:
                ISOException.throwIt(ISO7816.SW_INS_NOT_SUPPORTED);
        }
    }
